import assert from "node:assert/strict";
import {pathToFileURL} from "node:url";
import {join} from "node:path";
import {readFileSync} from "node:fs";
const root = process.argv[2];
const {createActivationPolicyResolver, classifyRuntimeMode} = await import(pathToFileURL(join(root,"src/foundry/activation-policy.mjs")));
const {createAutoModeConfirmationGateway} = await import(pathToFileURL(join(root,"src/foundry/auto-mode-confirmation-gateway.mjs")));
const w = {innerWidth:1600,innerHeight:900,matchMedia:()=>({matches:false})};
const desktop = {platform:"Linux x86_64",userAgent:"Mozilla Linux Firefox",maxTouchPoints:0};
const phone = {platform:"iPhone",userAgent:"Mozilla iPhone Mobile",maxTouchPoints:5};
const ipad = {platform:"MacIntel",userAgent:"Mozilla Macintosh",maxTouchPoints:5};
assert.equal(classifyRuntimeMode({window:w,navigator:desktop}),"desktop");
const make = navigator => createActivationPolicyResolver({getWindow:()=>w,getNavigator:()=>navigator});
const d = make(desktop);
assert.equal(d.resolve({mode:"auto"}).runtimeMode,"tablet");
assert.equal(d.resolve({mode:"desktop"}).active,false);
assert.equal(d.resolve({mode:"tablet"}).active,true);
assert.equal(make(phone).resolve({mode:"auto"}).runtimeMode,"phone");
assert.equal(make(ipad).resolve({mode:"auto"}).runtimeMode,"tablet");
const confirmation = createAutoModeConfirmationGateway({readPreferences:()=>({mode:"auto"}),resolvePolicy:p=>d.resolve(p),saveMode:async()=>{}});
assert.equal(confirmation.pending,true);
assert.equal(confirmation.suggestion(),"tablet");
assert.equal(confirmation.policy().active,false);
const manifest = JSON.parse(readFileSync(join(root,"module.json")));
assert.equal(manifest.id,"silber-hud-ve");
assert.equal(manifest.manifest,undefined);
assert.equal(manifest.download,undefined);
console.log("PASS: desktop physical identity; opt-in tablet/PC mode; native fallback; phone/iPad; confirmation; separate manifest");
